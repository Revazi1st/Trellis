def measure(text: str, size: float, weight: int = 400, mono: bool = False) -> float:
    """The estimated advance width of one line of text, in px."""
    if mono:
        return len(text) * size * MONO_EM
    table = _BOLD if weight >= 600 else _REGULAR
    units = 0
    for char in text:
        code = ord(char)
        units += table[code - 32] if 32 <= code <= 126 else _OTHER.get(char, 1000)
    return units / 1000 * size * SANS_MARGIN


def wrap(text: str, size: float, width: float, weight: int = 400,
         mono: bool = False) -> List[str]:
    """Word wrap to an estimated width, balanced: the narrowest width that needs no more lines than
    the full one, so a paragraph never ends on a stranded word."""
    lines = _greedy(text, size, width, weight, mono)
    if len(lines) < 2:
        return lines
    low, high = width / 2, width
    for _ in range(24):
        middle = (low + high) / 2
        if len(_greedy(text, size, middle, weight, mono)) <= len(lines):
            high = middle
        else:
            low = middle
    return _greedy(text, size, high, weight, mono)


def _greedy(text: str, size: float, width: float, weight: int, mono: bool) -> List[str]:
    """Greedy word wrap; a single word wider than the width keeps its own line."""
    lines: List[str] = []
    current = ""
    for word in text.split(" "):
        candidate = word if not current else f"{current} {word}"
        if not current or measure(candidate, size, weight, mono) <= width:
            current = candidate
        else:
            lines.append(current)
            current = word
    if current:
        lines.append(current)
    return lines


def num(value: float) -> str:
    """A coordinate as the SVG gets it: two decimals at most, no trailing zeros, never '-0'."""
    value = round(value, 2)
    if value == 0:
        return "0"
    return f"{value:.2f}".rstrip("0").rstrip(".")


