SLICE = "Invoices"  # the reference slice, docs/features/invoices.md


# A row's kind: "open" (an expanded folder), "folder" (collapsed to its file count), "file", or
# "context" (the first row of a column that continues a folder, naming it).
@dataclass(frozen=True)
class Row:
    depth: int
    name: str
    kind: str
    files: int = 0
    in_slice: bool = False
    slice_root: bool = False
    parents: Tuple[str, ...] = ()


def has_slice(node: Node) -> bool:
    return any(c.is_dir and (c.name == SLICE or has_slice(c)) for c in node.children)


def tree_rows(project: Node) -> List[Row]:
    """The abbreviation rule, applied to one project (see the module docstring)."""
    rows: List[Row] = []

    def ordered(children: List[Node]) -> List[Node]:
        return [c for c in children if c.is_dir] + [c for c in children if not c.is_dir]

    def visit(node: Node, depth: int, parents: Tuple[str, ...], levels: int,
              in_slice: bool) -> None:
        if not node.is_dir:
            rows.append(Row(depth, node.name, "file", in_slice=in_slice, parents=parents))
            return
        inner = parents + (node.name,)
        if in_slice:
            if levels > 0:
                rows.append(Row(depth, node.name, "open", in_slice=True, parents=parents))
                for child in ordered(node.children):
                    visit(child, depth + 1, inner, levels - 1, True)
            else:
                rows.append(Row(depth, node.name, "folder", node.files(), in_slice=True,
                                parents=parents))
        elif node.name == SLICE:
            rows.append(Row(depth, node.name, "open", in_slice=True, slice_root=True,
                            parents=parents))
            for child in ordered(node.children):
                visit(child, depth + 1, inner, 1, True)
        elif has_slice(node):
            rows.append(Row(depth, node.name, "open", parents=parents))
            for child in ordered(node.children):
                visit(child, depth + 1, inner, 0, False)
        else:
            rows.append(Row(depth, node.name, "folder", node.files(), parents=parents))

    for child in ordered(project.children):
        if not child.is_dir and child.name.endswith(".csproj"):
            continue
        visit(child, 0, (), 0, False)
    return rows


# --- Project references and AGENTS.md's dependency flow -------------------------------------------

def project_references() -> Dict[str, List[str]]:
    """Short project name -> the short names its ProjectReference items point at (each project is
    named by its .csproj file, as MSBuild names it)."""
    refs: Dict[str, List[str]] = {}
    for top in ("src", "tools"):
        for csproj in sorted((ROOT / top).rglob("*.csproj")):
            text = csproj.read_text(encoding="utf-8")
            targets = []
            for include in re.findall(r'<ProjectReference\s+Include="([^"]+)"', text):
                target = Path(include.replace("\\", "/"))
                targets.append(short(target.stem))
            refs[short(csproj.stem)] = sorted(set(targets))
    return refs


def agents_flow() -> List[Tuple[str, str]]:
    """The edges of AGENTS.md's dependency-flow block, as (from, to): 'from' references 'to'."""
    block = find("AGENTS.md", r"## Dependency flow[^\n]*\n+```\n(.*?)\n```",
                 "the Dependency flow block").group(1)
    edges: List[Tuple[str, str]] = []
    for line in block.splitlines():
        for chain in line.split(";"):
            tokens = re.findall(r"\{[^}]*\}|←|→|[A-Za-z][A-Za-z.]*", chain)
            if not tokens:
                continue
            groups, arrows = [], []
            for index, token in enumerate(tokens):
                if index % 2:
                    if token not in ("←", "→"):
                        raise RenderError("AGENTS.md: cannot read the dependency flow near "
                                          f"{token!r}")
                    arrows.append(token)
                else:
                    names = token.strip("{}").split("∥") if token.startswith("{") else [token]
                    groups.append([n.strip() for n in names])
            for left, direction, right in zip(groups, arrows, groups[1:]):
                for a in left:
                    for b in right:
                        edges.append((a, b) if direction == "→" else (b, a))
    if not edges:
        raise RenderError("AGENTS.md: the Dependency flow block names no edge")
    return edges


