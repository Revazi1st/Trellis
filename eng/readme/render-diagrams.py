def icon_markup(scale: float, x: float, y: float) -> List[str]:
    """.template.config/icon.svg, embedded: its elements in a group, its ids prefixed."""
    namespace = "{http://www.w3.org/2000/svg}"
    root = ET.fromstring(read_text(".template.config/icon.svg"))

    def serialise(element: ET.Element) -> str:
        tag = element.tag.replace(namespace, "")
        attrs = ""
        for key, value in element.attrib.items():
            if key == "id":
                value = f"trellis-mark-{value}"
            value = re.sub(r"url\(#([^)]+)\)", r"url(#trellis-mark-\1)", value)
            attrs += f' {key}="{escape(value, {chr(34): "&quot;"})}"'
        children = "".join(serialise(child) for child in element)
        return f"<{tag}{attrs}/>" if not children else f"<{tag}{attrs}>{children}</{tag}>"

    group = f'<g transform="translate({num(x)} {num(y)}) scale({num(scale)})">'
    return [group] + [f"  {serialise(child)}" for child in root] + ["</g>"]


