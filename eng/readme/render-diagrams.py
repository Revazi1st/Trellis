def annotate(message: str, file: Optional[str] = None) -> None:
    print(f"error: {message}", file=sys.stderr)
    if os.environ.get("GITHUB_ACTIONS") == "true":
        print(f"::error{f' file={file}' if file else ''}::{message}")


def check(rendered: Dict[str, str]) -> int:
    stale = 0
    run = f"run python3 {HERE_REL}/render-diagrams.py"
    for name, content in rendered.items():
        rel = f"{HERE_REL}/{name}"
        path = HERE / name
        if not path.is_file():
            annotate(f"{rel} is missing: {run} and commit it", rel)
            stale += 1
        elif path.read_bytes() != content.encode("utf-8"):
            annotate(f"{rel} no longer matches the repository: {run} and commit the result", rel)
            committed = path.read_text(encoding="utf-8").splitlines()
            diff = difflib.unified_diff(committed, content.splitlines(), "committed", "rendered",
                                        n=0, lineterm="")
            for line in list(diff)[:12]:
                print(f"    {line[:160]}", file=sys.stderr)
            stale += 1
    for path in sorted(HERE.glob("*.svg")):
        if path.name not in rendered and re.search(r"-(light|dark)\.svg$", path.name):
            rel = f"{HERE_REL}/{path.name}"
            annotate(f"{rel} is no longer drawn by render-diagrams.py: delete it", rel)
            stale += 1
    if stale:
        return 1
    print(f"README diagrams are current: {len(rendered)} SVGs in {HERE_REL}/ match the "
          "repository.")
    return 0


def write(rendered: Dict[str, str]) -> int:
    changed = 0
    for name, content in rendered.items():
        path = HERE / name
        data = content.encode("utf-8")
        if not path.is_file() or path.read_bytes() != data:
            path.write_bytes(data)
            changed += 1
            print(f"wrote {HERE_REL}/{name}")
    print(f"{changed} of {len(rendered)} SVGs changed.")
    return 0


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(
        description="Render the README's diagrams from the repository.")
    parser.add_argument("--check", action="store_true",
                        help="write nothing; exit 1 when a committed SVG differs from a fresh "
                             "render")
    args = parser.parse_args(argv)
    try:
        rendered = render_all()
    except RenderError as error:
        annotate(f"cannot render the README diagrams: {error}")
        return 2
    return check(rendered) if args.check else write(rendered)


if __name__ == "__main__":
    sys.exit(main())
