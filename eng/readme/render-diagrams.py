def read_text(rel: str) -> str:
    path = ROOT / rel
    if not path.is_file():
        raise RenderError(f"{rel} is missing")
    return path.read_text(encoding="utf-8")


def find(rel: str, pattern: str, what: str) -> "re.Match[str]":
    match = re.search(pattern, read_text(rel), re.S)
    if not match:
        raise RenderError(f"{rel}: cannot find {what}; the pictures name it, so update "
                          f"{HERE_REL}/render-diagrams.py with the code")
    return match


def glob_regex(pattern: str) -> "re.Pattern[str]":
    """A template.json glob as a regular expression: ** spans folders, * and ? stay inside one."""
    out, i = ["^"], 0
    while i < len(pattern):
        if pattern.startswith("**/", i):
            out.append("(?:.*/)?")
            i += 3
        elif pattern.startswith("/**", i) and i + 3 == len(pattern):
            out.append("(?:/.*)?")
            i += 3
        elif pattern.startswith("**", i):
            out.append(".*")
            i += 2
        elif pattern[i] == "*":
            out.append("[^/]*")
            i += 1
        elif pattern[i] == "?":
            out.append("[^/]")
            i += 1
        else:
            out.append(re.escape(pattern[i]))
            i += 1
    return re.compile("".join(out) + "$")


def evaluate(condition: str, values: Dict[str, bool]) -> bool:
    """A modifier condition such as (!IncludeUiTests || !IncludeUI), with the symbols' values."""
    tokens = re.findall(r"\(|\)|!|&&|\|\||[A-Za-z_][A-Za-z0-9_]*", condition)
    if "".join(tokens) != re.sub(r"\s+", "", condition):
        raise RenderError(f"template.json: cannot read the condition {condition!r}")
    position = 0

    def take() -> str:
        nonlocal position
        position += 1
        return tokens[position - 1]

    def peek() -> Optional[str]:
        return tokens[position] if position < len(tokens) else None

    def expression() -> bool:
        value = term()
        while peek() == "||":
            take()
            right = term()
            value = value or right
        return value

    def term() -> bool:
        value = factor()
        while peek() == "&&":
            take()
            right = factor()
            value = value and right
        return value

    def factor() -> bool:
        token = take()
        if token == "!":
            return not factor()
        if token == "(":
            value = expression()
            if take() != ")":
                raise RenderError(f"template.json: unbalanced condition {condition!r}")
            return value
        if token not in values:
            raise RenderError(f"template.json: the condition {condition!r} uses {token}, "
                              "which has no default")
        return values[token]

    result = expression()
    if position != len(tokens):
        raise RenderError(f"template.json: cannot read the condition {condition!r}")
    return result


@dataclass
class Template:
    defaults: Dict[str, bool]
    flags: Dict[str, str]
    excluded: List["re.Pattern[str]"]
    conditional: List[Tuple[str, "re.Pattern[str]"]]

    def ships(self, rel: str) -> bool:
        """True when a default `dotnet new trellis` generates this path."""
        return not any(rx.match(rel) for rx in self.excluded)

    def options(self, rel: str) -> Tuple[List[str], List[str]]:
        """The CLI flags a path depends on: those on by default, and those it needs switched on."""
        on, opt_in = [], []
        for condition, rx in self.conditional:
            if rx.match(rel):
                for symbol in sorted(set(re.findall(r"[A-Za-z_][A-Za-z0-9_]*", condition))):
                    flag = self.flags.get(symbol)
                    if flag is None:
                        raise RenderError(f"dotnetcli.host.json has no CLI flag for {symbol}")
                    (on if self.defaults[symbol] else opt_in).append(flag)
        return sorted(set(on)), sorted(set(opt_in))


def load_template() -> Template:
    config = json.loads(read_text(".template.config/template.json"))
    host = json.loads(read_text(".template.config/dotnetcli.host.json"))
    defaults = {name: symbol.get("defaultValue") == "true"
                for name, symbol in config["symbols"].items()
                if symbol.get("type") == "parameter" and symbol.get("datatype") == "bool"}
    flags = {name: "--" + info["longName"] for name, info in host["symbolInfo"].items()}
    source = config["sources"][0]
    excluded = [glob_regex(p) for p in source.get("exclude", [])]
    conditional: List[Tuple[str, "re.Pattern[str]"]] = []
    for modifier in source.get("modifiers", []):
        unknown = set(modifier) - {"condition", "exclude"}
        if unknown:
            raise RenderError(f"template.json: a modifier carries {sorted(unknown)}, which this "
                              f"script does not apply; teach load_template() in "
                              f"{HERE_REL}/render-diagrams.py")
        condition = modifier.get("condition", "")
        applies = evaluate(condition, defaults)
        for pattern in modifier.get("exclude", []):
            rx = glob_regex(pattern)
            conditional.append((condition, rx))
            if applies:
                excluded.append(rx)
    return Template(defaults, flags, excluded, conditional)


@dataclass
class Node:
    name: str
    rel: str
    is_dir: bool
    children: List["Node"] = field(default_factory=list)

    def files(self) -> int:
        return 1 if not self.is_dir else sum(child.files() for child in self.children)


def scan(rel: str, template: Template) -> Node:
    """A folder as the template ships it. Folders that ship no file are left out, as git leaves
    them, and so are dot-entries: no project tracks one, and an IDE's local .idea/ or .vscode/
    must not change the picture."""
    node = Node(rel.rsplit("/", 1)[-1], rel, True)
    for entry in sorted((ROOT / rel).iterdir(), key=lambda p: (p.name.casefold(), p.name)):
        child_rel = f"{rel}/{entry.name}"
        if entry.name.startswith(".") or entry.is_symlink() or not template.ships(child_rel):
            continue
        if entry.is_dir():
            child = scan(child_rel, template)
            if child.files():
                node.children.append(child)
        elif entry.is_file():
            node.children.append(Node(entry.name, child_rel, False))
    return node


def project_dirs(top: str, template: Template) -> List[str]:
    """Every shipped folder under top that holds a .csproj."""
    found = []
    for csproj in sorted((ROOT / top).rglob("*.csproj")):
        rel = csproj.parent.relative_to(ROOT).as_posix()
        if template.ships(csproj.relative_to(ROOT).as_posix()):
            found.append(rel)
    return found


def short(project_rel: str) -> str:
    """Trellis.Api.Common -> Api.Common, the names AGENTS.md and the docs use."""
    name = project_rel.rsplit("/", 1)[-1]
    return name[len("Trellis."):] if name.startswith("Trellis.") else name


